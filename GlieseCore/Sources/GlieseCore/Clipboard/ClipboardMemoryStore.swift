import CryptoKit
import Foundation

public struct ClipboardEntry: Equatable, Identifiable, Sendable {
    public enum Kind: String, Equatable, Sendable {
        case text
        case link
        case image
    }

    public enum Payload: Equatable, Sendable {
        case text(String)
        case link(String)
        case image(data: Data, width: Int, height: Int, uti: String)

        public var byteCount: Int {
            switch self {
            case .text(let s), .link(let s):
                return s.utf8.count
            case .image(let data, _, _, _):
                return data.count
            }
        }
    }

    public let id: UUID
    public let kind: Kind
    public let payload: Payload
    public let contentFingerprint: String
    public let capturedAt: Date
    public let sourceAppBundleID: String?
    public let sourceAppName: String?
    public var isPinned: Bool

    public init(
        id: UUID = UUID(),
        kind: Kind,
        payload: Payload,
        contentFingerprint: String,
        capturedAt: Date = Date(),
        sourceAppBundleID: String? = nil,
        sourceAppName: String? = nil,
        isPinned: Bool = false
    ) {
        self.id = id
        self.kind = kind
        self.payload = payload
        self.contentFingerprint = contentFingerprint
        self.capturedAt = capturedAt
        self.sourceAppBundleID = sourceAppBundleID
        self.sourceAppName = sourceAppName
        self.isPinned = isPinned
    }

    public var previewText: String {
        switch payload {
        case .text(let s), .link(let s):
            return s
        case .image(_, let width, let height, _):
            return "Image (\(width)×\(height))"
        }
    }
}

public struct ClipboardMemoryStore: Sendable {
    public static let defaultMaxEntries = 50
    public static let defaultMaxTotalBytes = 32 * 1024 * 1024
    public static let defaultMaxTextBytes = 1 * 1024 * 1024
    public static let defaultMaxImageBytes = 5 * 1024 * 1024
    public static let defaultMaxImagePixels = 4096 * 4096

    public static let sensitivePasteboardTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "de.onyxbits.Textreme.Confidential"
    ]

    public enum IngestResult: Equatable, Sendable {
        case stored(UUID)
        case ignoredCaptureDisabledOrPaused
        case ignoredUnchangedPasteboardCount
        case ignoredSensitivePasteboardType
        case ignoredExcludedSourceApp
        case ignoredEmptyPayload
        case ignoredPayloadExceedsLimit
        case ignoredImageDimensionsExceedLimit
        case ignoredDuplicateConsecutiveOrSelfCopy
        case rejectedAllPinnedCapReached
    }

    public let maxEntries: Int
    public let maxTotalBytes: Int
    public let maxTextBytes: Int
    public let maxImageBytes: Int
    public let maxImagePixels: Int

    public private(set) var isOptedIn: Bool = false
    public private(set) var isPaused: Bool = false
    public private(set) var lastObservedChangeCount: Int?
    public private(set) var entries: [ClipboardEntry] = []
    public private(set) var totalBytes: Int = 0
    public var ignoredAppBundleIDs: Set<String>
    private var lastSelfCopiedFingerprint: String?

    public init(
        maxEntries: Int = ClipboardMemoryStore.defaultMaxEntries,
        maxEntryBytes: Int? = nil,
        maxTotalBytes: Int = ClipboardMemoryStore.defaultMaxTotalBytes,
        maxTextBytes: Int = ClipboardMemoryStore.defaultMaxTextBytes,
        maxImageBytes: Int = ClipboardMemoryStore.defaultMaxImageBytes,
        maxImagePixels: Int = ClipboardMemoryStore.defaultMaxImagePixels,
        ignoredAppBundleIDs: Set<String> = [
            "com.1password.1password",
            "com.agilebits.onepassword7",
            "com.bitwarden.desktop",
            "com.apple.keychainaccess",
            "com.apple.Passwords"
        ]
    ) {
        self.maxEntries = maxEntries
        self.maxTotalBytes = maxTotalBytes
        self.maxTextBytes = maxEntryBytes ?? maxTextBytes
        self.maxImageBytes = maxEntryBytes ?? maxImageBytes
        self.maxImagePixels = maxImagePixels
        self.ignoredAppBundleIDs = ignoredAppBundleIDs
    }

    /// Enables capture and sets baseline `changeCount` so pre-existing clipboard contents are never imported.
    public mutating func setOptIn(_ enabled: Bool, currentChangeCount: Int) {
        isOptedIn = enabled
        lastObservedChangeCount = currentChangeCount
        if !enabled {
            clearAll()
        }
    }

    /// Pauses or resumes capture. Resuming re-anchors `lastObservedChangeCount` so items copied while paused are never backfilled.
    public mutating func setPaused(_ paused: Bool, currentChangeCount: Int) {
        isPaused = paused
        lastObservedChangeCount = currentChangeCount
    }

    public mutating func markSelfCopy(entryID: UUID, newChangeCount: Int) {
        lastObservedChangeCount = newChangeCount
        if let entry = entries.first(where: { $0.id == entryID }) {
            lastSelfCopiedFingerprint = entry.contentFingerprint
        }
    }

    public mutating func ingest(
        changeCount: Int,
        pasteboardTypes: Set<String>,
        payload: ClipboardEntry.Payload,
        sourceAppBundleID: String? = nil,
        sourceAppName: String? = nil,
        capturedAt: Date = Date()
    ) -> IngestResult {
        guard isOptedIn, !isPaused else {
            return .ignoredCaptureDisabledOrPaused
        }

        if let baseline = lastObservedChangeCount, changeCount <= baseline {
            return .ignoredUnchangedPasteboardCount
        }
        lastObservedChangeCount = changeCount

        if !pasteboardTypes.isDisjoint(with: Self.sensitivePasteboardTypes) {
            return .ignoredSensitivePasteboardType
        }

        if let bundle = sourceAppBundleID, ignoredAppBundleIDs.contains(bundle) {
            return .ignoredExcludedSourceApp
        }

        let kind: ClipboardEntry.Kind
        let byteCount = payload.byteCount
        switch payload {
        case .text(let s), .link(let s):
            let trimmed = s.trimmingCharacters(in: .whitespacesAndNewlines)
            guard !trimmed.isEmpty else { return .ignoredEmptyPayload }
            guard byteCount <= maxTextBytes, byteCount <= maxTotalBytes else {
                return .ignoredPayloadExceedsLimit
            }
            if Self.looksLikeHTTPURL(trimmed) {
                kind = .link
            } else {
                kind = .text
            }
        case .image(let data, let width, let height, _):
            guard !data.isEmpty else { return .ignoredEmptyPayload }
            guard byteCount <= maxImageBytes, byteCount <= maxTotalBytes else {
                return .ignoredPayloadExceedsLimit
            }
            guard width > 0, height > 0, (width * height) <= maxImagePixels else {
                return .ignoredImageDimensionsExceedLimit
            }
            kind = .image
        }

        let fingerprint = Self.computeFingerprint(for: payload)
        if fingerprint == lastSelfCopiedFingerprint {
            lastSelfCopiedFingerprint = nil
            return .ignoredDuplicateConsecutiveOrSelfCopy
        }
        if entries.first?.contentFingerprint == fingerprint {
            return .ignoredDuplicateConsecutiveOrSelfCopy
        }

        // Evict oldest unpinned entries until both count and byte budget have room
        while (entries.count >= maxEntries || (totalBytes + byteCount) > maxTotalBytes) {
            guard let evictIdx = entries.lastIndex(where: { !$0.isPinned }) else {
                return .rejectedAllPinnedCapReached
            }
            let removed = entries.remove(at: evictIdx)
            totalBytes = max(0, totalBytes - removed.payload.byteCount)
        }

        let normalizedPayload: ClipboardEntry.Payload
        if case .text(let s) = payload, kind == .link {
            normalizedPayload = .link(s.trimmingCharacters(in: .whitespacesAndNewlines))
        } else {
            normalizedPayload = payload
        }

        let entry = ClipboardEntry(
            kind: kind,
            payload: normalizedPayload,
            contentFingerprint: fingerprint,
            capturedAt: capturedAt,
            sourceAppBundleID: sourceAppBundleID,
            sourceAppName: sourceAppName,
            isPinned: false
        )
        entries.insert(entry, at: 0)
        totalBytes += byteCount
        return .stored(entry.id)
    }

    public mutating func togglePin(id: UUID) {
        guard let idx = entries.firstIndex(where: { $0.id == id }) else { return }
        entries[idx].isPinned.toggle()
    }

    public mutating func remove(id: UUID) {
        guard let idx = entries.firstIndex(where: { $0.id == id }) else { return }
        let removed = entries.remove(at: idx)
        totalBytes = max(0, totalBytes - removed.payload.byteCount)
    }

    /// Wipes all entries (including pinned) on explicit Clear All or application Quit.
    public mutating func clearAll() {
        entries.removeAll(keepingCapacity: false)
        totalBytes = 0
        lastSelfCopiedFingerprint = nil
    }

    public mutating func prepareCopyToPasteboard(id: UUID) -> ClipboardEntry? {
        guard let entry = entries.first(where: { $0.id == id }) else { return nil }
        lastSelfCopiedFingerprint = entry.contentFingerprint
        return entry
    }

    public mutating func capture(
        payload: ClipboardEntry.Payload,
        pasteboardTypes: Set<String>,
        sourceAppBundleID: String? = nil,
        sourceAppName: String? = nil,
        capturedAt: Date = Date()
    ) -> IngestResult {
        if !isOptedIn {
            setOptIn(true, currentChangeCount: (lastObservedChangeCount ?? 0))
        }
        let count = (lastObservedChangeCount ?? 0) + 1
        return ingest(
            changeCount: count,
            pasteboardTypes: pasteboardTypes,
            payload: payload,
            sourceAppBundleID: sourceAppBundleID,
            sourceAppName: sourceAppName,
            capturedAt: capturedAt
        )
    }

    public func filteredEntries(query: String) -> [ClipboardEntry] {
        let q = query.trimmingCharacters(in: .whitespacesAndNewlines).lowercased()
        let ordered = entries.sorted { lhs, rhs in
            if lhs.isPinned != rhs.isPinned {
                return lhs.isPinned && !rhs.isPinned
            }
            return lhs.capturedAt > rhs.capturedAt
        }
        guard !q.isEmpty else { return ordered }
        return ordered.filter { entry in
            if entry.previewText.lowercased().contains(q) { return true }
            if let app = entry.sourceAppName?.lowercased(), app.contains(q) { return true }
            if let bundle = entry.sourceAppBundleID?.lowercased(), bundle.contains(q) { return true }
            return false
        }
    }

    private static func looksLikeHTTPURL(_ raw: String) -> Bool {
        guard !raw.contains(where: \.isWhitespace),
              let url = URL(string: raw),
              let scheme = url.scheme?.lowercased(),
              (scheme == "http" || scheme == "https"),
              let host = url.host,
              !host.isEmpty else {
            return false
        }
        return true
    }

    public static func computeFingerprint(for payload: ClipboardEntry.Payload) -> String {
        var hasher = SHA256()
        switch payload {
        case .text(let s), .link(let s):
            hasher.update(data: Data("text:".utf8))
            hasher.update(data: Data(s.utf8))
        case .image(let data, let width, let height, _):
            hasher.update(data: Data("image:\(width)x\(height):".utf8))
            hasher.update(data: data)
        }
        let digest = hasher.finalize()
        return digest.map { String(format: "%02x", $0) }.joined()
    }
}
